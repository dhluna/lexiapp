// Generates Lexi's share QR code: the module matrix shared by web and mobile
// (packages/core/src/data/share.ts) and the downloadable files (apps/web/public/qr/).
// The PNG is decoded back at the end to make sure the code with the logo still scans.
// Usage: node scripts/generate-qr.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import jsQR from "jsqr";
import QRCode from "qrcode";
import sharp from "sharp";
import { renderQrSvg } from "../packages/core/src/domain/qr.ts";

const SHARE_URL = "https://lexiapp.app";
const SHARE_TEXT = "Estoy aprendiendo vocabulario en inglés con Lexi. Es gratis:";

// Error correction H (30 %): the logo in the middle covers part of the code.
const { modules } = QRCode.create(SHARE_URL, { errorCorrectionLevel: "H", version: 3 });
const rows = Array.from({ length: modules.size }, (_, y) =>
  Array.from({ length: modules.size }, (_, x) => (modules.get(y, x) ? "1" : "0")).join(""),
);

writeFileSync(
  "packages/core/src/data/share.ts",
  `// Generated by scripts/generate-qr.mjs: do not edit by hand.

/** Page that the share links and the QR code open. */
export const SHARE_URL = ${JSON.stringify(SHARE_URL)};

/** Message that goes before the link when sharing. */
export const SHARE_TEXT = ${JSON.stringify(SHARE_TEXT)};

/** QR code of SHARE_URL (error correction H), one string of "0"/"1" per row. */
export const QR_MODULES: readonly string[] = [
${rows.map((r) => `  "${r}",`).join("\n")}
];
`,
);

mkdirSync("apps/web/public/qr", { recursive: true });
const svg = renderQrSvg(rows, { pixels: 1024, title: "lexiapp.app" });
writeFileSync("apps/web/public/qr/lexiapp-qr.svg", svg);
const png = await sharp(Buffer.from(svg)).resize(1024, 1024).png().toBuffer();
writeFileSync("apps/web/public/qr/lexiapp-qr.png", png);

const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const decoded = jsQR(new Uint8ClampedArray(data), info.width, info.height);
if (decoded?.data !== SHARE_URL) throw new Error(`The QR code does not scan: ${decoded?.data}`);
console.log(`QR ${modules.size}×${modules.size} → ${SHARE_URL} (verified)`);
